def explain_error(line: str) -> str:
    """一条 `ERR ...` 回复的中文说明，原话附在括号里。"""
    text = line.strip()
    for prefix, meaning in _ERRORS:
        if text.startswith(prefix):
            return f"{meaning}（飞控原话：{text}）"
    return f"飞控拒绝了这条命令（飞控原话：{text}）"


